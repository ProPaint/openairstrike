// A --paks directory without pak0.apk: a pak0.apk built from its loose files (issue 170),
// kept under root/third_party_local/built/<key>/, or in the directory itself when the root
// cannot be written. Returns the path, or "" with a message.
std::string builtPak0(const std::string& root, const std::string& paksDir, const GameProfile** game, std::string* error) {
    const std::vector<LooseFile> files = looseFilesUnder(paksDir);
    double coverage = 0;
    const GameProfile* g = gameOfLooseFiles(files, *game, &coverage);
    if (!g) {
        char pct[32];
        std::snprintf(pct, sizeof pct, "%.1f", coverage * 100.0);
        *error = paksDir + " has no pak0.apk, and its loose files cover " + pct + " % of " +
                 (*game ? std::string((*game)->title) + "'s" : "any game's") + " pak0.apk entries (" +
                 std::to_string(static_cast<int>(kLooseMinCoverage * 100.0)) + " % needed; tools/pak_entries/ lists them)";
        return std::string();
    }
    *game = g;
    const std::string candidates[2] = {join(root, std::string("third_party_local/built/") + g->key + "/pak0.apk"),
                                       join(paksDir, "pak0.apk")};
    for (const std::string& out : candidates) {
        if (isFile(out) && identifyPak0File(out) == g) {
            AS3D_INFO("paks: %s has no pak0.apk: using the one built earlier from its files, %s", paksDir.c_str(), out.c_str());
            return out;
        }
        if (!makeDirectories(dirOfFile(out))) continue;
        int count = 0;
        std::string why;
        if (!writePak0FromLooseFiles(files, *g, out, &count, &why)) {
            AS3D_WARN("paks: cannot build %s (%s)", out.c_str(), why.c_str());
            continue;
        }
        AS3D_INFO("paks: %s has no pak0.apk: built it from %d loose files (%.1f %% of %s's entries) into %s", paksDir.c_str(),
                  count, coverage * 100.0, g->title, out.c_str());
        return out;
    }
    *error = "cannot write a pak0.apk built from the files of " + paksDir + " (tried " + candidates[0] + " and " + candidates[1] + ")";
    return std::string();
}

