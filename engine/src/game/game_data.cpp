bool exists(const std::string& path) {
    std::error_code ec;
    return fs::exists(fs::path(path), ec);
}

bool isFile(const std::string& path) {
    std::error_code ec;
    return fs::is_regular_file(fs::path(path), ec);
}

std::string join(const std::string& a, const std::string& b) { return a.empty() ? b : a + "/" + b; }

std::string dirOfFile(const std::string& path) {
    size_t slash = path.find_last_of('/');
    return slash == std::string::npos ? std::string(".") : path.substr(0, slash);
}

// Fills the parts that depend on the data directory and the extracted directory.
void fillFiles(GameData& d) {
    d.hasExtracted = exists(join(d.extractedDir, "maps/levels.txt"));
    for (const char* const* p = d.game->paks; *p; ++p) {
        std::string path = join(d.dataDir, *p);
        if (exists(path)) d.paks.push_back(path);
        else if (!pakIsOptional(*d.game, *p)) d.missing.push_back(path);
    }
    if (!d.hasExtracted) d.missing.push_back(join(d.extractedDir, "maps/levels.txt"));
    std::string s = join(d.dataDir, "Settings.xml");
    if (exists(s)) d.settingsXml = s;
    std::string t = join(d.extractedDir, d.game->textsFile);
    if (exists(t)) d.textsFile = t;
    std::string l = join(d.dataDir, "gfx/logo2s.tga");
    if (exists(l)) d.logoFile = l;
}

std::string knownKeys() {
    std::string s;
    for (int i = 0; i < kGameCount; ++i) {
        if (i) s += ", ";
        s += gameProfile(static_cast<GameId>(i)).key;
    }
    return s;
}

std::string detectedKeys(const std::vector<GameData>& found) {
    std::string s;
    for (const GameData& g : found) {
        if (!s.empty()) s += ", ";
        s += g.game->key;
    }
    return s.empty() ? "none" : s;
}

std::string whereFound(const GameData& d) {
    std::string s;
    if (!d.paks.empty()) s = d.dataDir + " (" + std::to_string(d.paks.size()) + " paks)";
    if (d.hasExtracted) s += (s.empty() ? "" : ", ") + d.extractedDir + " (extracted)";
    return s;
}

// ---- the reference names

std::vector<std::string> parseNames(const std::string& text) {
    std::vector<std::string> names;
    size_t p = 0;
    while (p < text.size()) {
        size_t e = text.find('\n', p);
        if (e == std::string::npos) e = text.size();
        std::string line = text.substr(p, e - p);
        if (!line.empty() && line.back() == '\r') line.pop_back();
        if (!line.empty()) names.push_back(normalizePakEntryName(line));
        p = e + 1;
    }
    std::sort(names.begin(), names.end());
    names.erase(std::unique(names.begin(), names.end()), names.end());
    return names;
}

bool readText(const std::string& path, std::string* out) {
    std::FILE* f = std::fopen(path.c_str(), "rb");
    if (!f) return false;
    char buf[65536];
    size_t n;
    out->clear();
    while ((n = std::fread(buf, 1, sizeof buf, f)) > 0) out->append(buf, n);
    const bool ok = !std::ferror(f);
    std::fclose(f);
    return ok;
}

// Reads the lists of `dir` into g_names; how many were read.
int loadNamesFrom(const std::string& dir) {
    int loaded = 0;
    for (int i = 0; i < kGameCount; ++i) {
        const GameProfile& g = gameProfile(static_cast<GameId>(i));
        for (const char* const* p = g.paks; *p; ++p) {
            const std::string pak = *p;
            const std::string stem = pak == "pak0.apk" ? std::string(g.key) : std::string(g.key) + "." + pak.substr(0, pak.size() - 4);
            std::string text;
            if (!readText(join(dir, stem + ".txt"), &text)) continue;
            g_names[{i, pak}] = parseNames(text);
            ++loaded;
        }
    }
    return loaded;
}

void ensureNamesLoaded() {
    if (g_namesLoaded) return;
    g_namesLoaded = true;
    const char* env = std::getenv("AS3D_PAK_ENTRIES");
    if (env && *env && loadNamesFrom(env) > 0) return;
#ifdef AS3D_REPO_ROOT
    loadNamesFrom(std::string(AS3D_REPO_ROOT) + "/tools/pak_entries");
#endif
}

size_t intersectionSize(const std::vector<std::string>& a, const std::vector<std::string>& b) {
    size_t n = 0, i = 0, j = 0;
    while (i < a.size() && j < b.size()) {
        const int c = a[i].compare(b[j]);
        if (c == 0) { ++n; ++i; ++j; }
        else if (c < 0) ++i;
        else ++j;
    }
    return n;
}

double jaccard(const std::vector<std::string>& a, const std::vector<std::string>& b) {
    if (a.empty() && b.empty()) return 1.0;
    const size_t both = intersectionSize(a, b);
    return static_cast<double>(both) / static_cast<double>(a.size() + b.size() - both);
}

std::string namesFingerprint(const std::vector<std::string>& names) {
    Sha256 h;
    for (size_t i = 0; i < names.size(); ++i) {
        if (i) h.update("\n", 1);
        h.update(names[i].data(), names[i].size());
    }
    return h.hexDigest();
}

