// The PICA WorldRenderer (as3d/world_render.h), 3DS only: the same public API as the GL one
// (engine/src/render/gles/world_render.cpp), the same neutral entity pass (WorldScene,
// engine/src/render/world_scene.h), the passes the PICA backend has so far.
//
// prepare(), once per frame: the terrain follows the world's craters (TerrainRenderer::update),
// WorldScene::prepare reads the world (camera, cull volume, lighting, dynamic lights, the model,
// sprite and particle lists, the shadow requests), the shadows are placed (at most one late
// silhouette generated, the blob for those not ready; their draped geometry cut from the
// terrain), then the two mesh passes are built (pica::MeshPass begin / submit / finish: the
// opaque list; the transparent then the effect list), all CPU work, nothing drawn.
//
// draw(eye), per eye, in the GL pass order: pass 0 clear to the fog colour (black without fog),
// W-buffer depth mapping for the near plane and the level fog; projection = the eye's
// picaEyeProjection with the CENTRAL view (citro3d's Mtx_PerspStereoTilt carries the eye
// translation); pass 2 terrain, pass 5 shadows, pass 6 opaque list, passes 8 and 9 transparent
// and effect lists, pass 10 particles, pass 12 sprites (health bars included). The particle,
// sprite and shadow vertices are built by the first eye of a frame and reused by the second.
//
// Shadows (shadow_pica.h): the silhouettes are CPU-rasterised A8 textures in linear memory,
// generated by precache(): the placements' (in their own rotation; the GL beginLevel's set) and
// the closure's planar ones; the 12 rotations of the closure's projected ones only with
// pica::setShadowPrecacheRotations(true), as the GL precache (too slow on the 3DS CPU: 18 s for
// mission 1 under Azahar). One first seen later is generated in prepare(), at most one per frame,
// and drawn from the next frame; until then the shadow is the blob over the same rectangle.
// Unlike the GL beginLevel, the placements' silhouettes come with precache() (precache=0 then
// shows the late path for every shadow). Projected shadows never move: their draped geometry is
// kept between frames (until a crater changes the terrain); planar ones are draped every frame.
//
// Ground marks and skid trails (pass 4, ground_marks_pica.h): the marks' draped geometry is kept
// until the set changes or a crater changes the terrain; the skid trails are rebuilt each frame;
// both are drawn per eye between the terrain and the shadows, as the GL renderer.
//
// Water (pass 7, water_renderer_pica.h, drawn per eye after the opaque list): the first game's
// flat scrolling plane, or the sequels' wave grid (RenderRules::water; the surface built as the
// GL beginLevel does, its dry vertices following the craters, the wave animated on the CPU per
// visible chunk, M5.1) and lightning bolts (lightning_renderer_pica.h, after the effect list,
// before the particles; the bolts are built in prepare and copied to the arena by the first eye).
//
// Environment maps (M3.4) draw inside the mesh passes (mesh_renderer_pica.h, shaders/env.v.pica)
// with the central view and the frame's time.
//
// Textures: the 4.2 MB VRAM budget (texture_budget.h) is filled in creation order: the terrain's
// textures at beginLevel first, then precache() puts the particle textures, then the level
// closure's meshes and skins in definition order; whatever does not fit goes to linear memory.
