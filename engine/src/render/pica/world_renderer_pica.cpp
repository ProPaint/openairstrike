// The passes of draw() in the pass profile (pass_profile.h): start(p) closes the running pass
// and opens p; each adds its CPU ticks and the draw calls and vertices it added to the frame's
// WorldRenderStats.
class PassMeter {
public:
    explicit PassMeter(const WorldRenderStats& st) : s_(st) {}
    ~PassMeter() { stop(); }
    void start(Pass p) {
        stop();
        active_ = true;
        p_ = p;
        d0_ = s_.drawCalls;
        v0_ = s_.vertices;
        t0_ = svcGetSystemTick();
    }
    void stop() {
        if (!active_) return;
        active_ = false;
        passProfile().add(p_, svcGetSystemTick() - t0_, s_.drawCalls - d0_, s_.vertices - v0_);
    }

private:
    const WorldRenderStats& s_;
    Pass p_ = Pass::Clear;
    bool active_ = false;
    u64 t0_ = 0;
    int d0_ = 0, v0_ = 0;
};
u64 systemTick() { return svcGetSystemTick(); }

// The parts of prepare() in the pass profile (the prep_* entries): lap(p, n) adds the ticks since
// the last lap to p, with n items.
class PrepMeter {
public:
    PrepMeter() : t_(svcGetSystemTick()) {}
    void lap(Pass p, int items = 0) {
        const u64 now = svcGetSystemTick();
        passProfile().add(p, now - t_, items, 0);
        t_ = now;
    }

private:
    u64 t_;
};
