struct WorldRenderer::Impl {
    Vfs* vfs = nullptr;
    const DefDatabase* db = nullptr;
    std::unique_ptr<ResourceCache> cache;
    WorldScene scene;
    pica::MeshPass opaquePass, restPass;
    ParticleRenderer particles;
    SpriteRenderer sprites;
    std::unique_ptr<TerrainRenderer> terrain;
    const Terrain* terrainOf = nullptr;
    RenderRules rules = renderRules(GameId::AirStrike3D);
    bool haveTerrain = false; // of the prepared frame

    // Shadows (shadow_pica.h). One entry per (mesh, skin texture, kind, quality, steps): the GL
    // cache's model|skin|kind|quality|steps without the strings (the mesh stands for its path,
    // the texture for the skin that is rasterised). `bounds` exists from the first request (the
    // blob's rectangle), `map` once generated.
    ShadowRenderer shadows;
    pica::ShadowPass shadowPass;
    pica::MarkPass markPass;
    pica::WaterPass waterPass;
    pica::LightningPass lightningPass;
    SkidTrailParams skidParams;
    Vec3 towardsSun{0.0f, 0.0f, 1.0f};
    struct ShadowEntry {
        std::unique_ptr<ShadowMap> map;
        ShadowBounds bounds;
        ShadowKind kind = ShadowKind::Planar;
        bool hasBounds = false;
        bool tried = false; // generate() was called (map null: it failed)
        u32 readyAt = 0;    // the prepare() serial from which the map is drawn
        pica::ShadowAtlasRef atlas; // the map's cell in an atlas page (page null: its own texture)
    };
    struct ShadowKey {
        const GpuMesh* mesh;
        const Texture2D* skin;
        int spec; // kind | quality << 2 | steps << 4
        bool operator==(const ShadowKey& o) const { return mesh == o.mesh && skin == o.skin && spec == o.spec; }
    };
    struct ShadowKeyHash {
        size_t operator()(const ShadowKey& k) const {
            size_t h = std::hash<const void*>()(k.mesh);
            h ^= std::hash<const void*>()(k.skin) + 0x9e3779b9u + (h << 6) + (h >> 2);
            return h ^ (static_cast<size_t>(k.spec) * 0x85ebca6bu);
        }
    };
    std::unordered_map<ShadowKey, ShadowEntry, ShadowKeyHash> shadowMaps;
    int lateShadowMaps = 0;
    u32 prepareSerial = 0;
    // The CPU alpha of the skins that have one (Material::texturePath, reloaded), by texture.
    std::unordered_map<const Texture2D*, std::unique_ptr<ShadowSkin>> skins;

    static ShadowKey shadowKey(const GpuMesh& mesh, const Material& mat, const ShadowSpec& ss, int steps) {
        // Only a skin with alpha changes the silhouette: opaque skins share the mesh's.
        return ShadowKey{&mesh, mat.textureHasAlpha ? mat.texture : nullptr,
                         static_cast<int>(ss.kind) | static_cast<int>(ss.quality) << 2 | steps << 4};
    }
    // Registers the CPU skin of `mat` for generate() (only skins with an alpha channel matter).
    void noteSkin(const Material& mat) {
        if (!mat.texture || !mat.textureHasAlpha || mat.texturePath.empty() || skins.count(mat.texture)) return;
        LoadStats::Site site; // part of the shadow, not a load of its own
        Blob blob;
        Image img;
        std::unique_ptr<ShadowSkin> sk;
        if (vfs->read(mat.texturePath, blob) && decodeTga(blob.data(), blob.size(), img)) sk.reset(new ShadowSkin(img));
        if (sk && (!sk->valid() || sk->opaque())) sk.reset();
        skins.emplace(mat.texture, std::move(sk));
    }
    // The entry of a key; its silhouette is generated now when `generate` (outside frames).
    ShadowEntry& shadowEntry(const GpuMesh& mesh, const Material& mat, const ShadowKey& key, const ShadowSpec& ss,
                             int steps, bool generate) {
        ShadowEntry& e = shadowMaps[key];
        if (!e.hasBounds) {
            e.hasBounds = true;
            e.kind = ss.kind;
            if (!mesh.model.faces.empty()) e.bounds = computeShadowBounds(mesh.model, ss.kind, towardsSun, steps);
        }
        if (generate && !e.tried) {
            e.tried = true;
            noteSkin(mat);
            std::unique_ptr<ShadowMap> map(new ShadowMap());
            if (shadows.generate(mesh.model, mat.texture, ss.kind, towardsSun, steps, ss.quality, *map)) {
                e.map = std::move(map);
                e.atlas = pica::lastShadowAtlasRef();
            }
            e.readyAt = prepareSerial + 1;
        }
        return e;
    }
    // WorldScene's shadow hook (precache): ready at once.
    void precacheShadow(const GpuMesh& mesh, const Material& mat, const ShadowSpec& ss, int steps) {
        if (ss.kind == ShadowKind::Planar) steps = 0;
        ShadowEntry& e = shadowEntry(mesh, mat, shadowKey(mesh, mat, ss, steps), ss, steps, true);
        e.readyAt = 0;
    }
    int shadowMapCount() const {
        int n = 0;
        for (const auto& kv : shadowMaps) n += kv.second.map ? 1 : 0;
        return n;
    }
};

WorldRenderer::WorldRenderer() : impl_(new Impl) {}
WorldRenderer::~WorldRenderer() = default;

bool WorldRenderer::init(Vfs& vfs, const DefDatabase& db, std::string* error) {
    Impl& im = *impl_;
    im.vfs = &vfs;
    im.db = &db;
    im.cache.reset(new ResourceCache(vfs));
    im.scene.init(*im.cache, vfs, db);
    im.scene.profile.clock = &pica::systemTick;
    if (!im.particles.init(vfs, error)) return false;
    if (!im.sprites.init(error)) return false;
    if (!im.shadows.init(error)) return false;
    if (!im.shadowPass.init()) {
        if (error) *error = "pica world: cannot create the shadow blob";
        return false;
    }
    pica::setShadowSkinSource([&im](const Texture2D* t) -> const ShadowSkin* {
        auto it = im.skins.find(t);
        return it != im.skins.end() ? it->second.get() : nullptr;
    });
    im.scene.resolveHealthBar(defaultGameRules());
    return true;
}

bool WorldRenderer::beginLevel(const World& world, std::string* error) {
    Impl& im = *impl_;
    im.scene.resolveHealthBar(world.rules());
    im.rules = renderRulesFor(world.rules());
    im.cache->setMissingTextureWhite(im.rules.missingTextureWhite);
    im.shadows.setRules(im.rules);
    im.shadowPass.setMultiply(im.rules.shadowMultiply);
    im.terrain.reset();
    im.terrainOf = nullptr;
    im.shadowMaps.clear();
    im.skins.clear();
    im.shadowPass.invalidate();
    im.markPass.reset();
    im.waterPass.reset();
    im.lightningPass.reset();
    im.skidParams = skidTrailParams(world.rules());
    im.lateShadowMaps = 0;
    pica::resetShadowPicaStats();
    im.scene.beginLevel(world, im.rules);
    const Terrain* t = world.terrain();
    if (!t) return true;
    std::unique_ptr<TerrainRenderer> tr(new TerrainRenderer());
    if (!tr->build(*t, *im.vfs, error, im.rules)) return false;
    im.terrain = std::move(tr);
    im.terrainOf = t;
    if (im.rules.water == WaterStyle::WaveGrid) {
        // As the GL: the shine texture is not in TerrainStyle, the level's definition has it.
        std::string shine;
        for (const LevelDef& d : im.db->levels())
            if (d.id == t->style().id) shine = d.waterShine;
        const WaterSurface surface = buildWaterSurface(*t, true, shine);
        if (!im.waterPass.build(*t, *im.vfs, &surface, TerrainGridView::of(*t), error)) return false;
    } else if (!im.waterPass.build(*t, *im.vfs, nullptr, TerrainGridView(), error)) {
        return false;
    }
    const TerrainStyle& st = t->style();
    const Vec3 sun{st.sun[3], st.sun[4], st.sun[5]};
    im.towardsSun = length(sun) > 1e-6f ? normalize(sun) : Vec3{0.0f, 0.0f, 1.0f};
    const pica::TerrainPicaStats& ts = pica::terrainPicaStats();
    AS3D_INFO("pica world: terrain %d chunks, %d textures %.1f KB (VRAM %.1f KB, linear %.1f KB); all passes on "
              "the PICA",
              ts.chunks, ts.textures, static_cast<double>(ts.textureBytes) / 1024.0,
              static_cast<double>(ts.textureVramBytes) / 1024.0, static_cast<double>(ts.textureLinearBytes) / 1024.0);
    return true;
}

PrecacheReport WorldRenderer::precache(const World& world, const DefDatabase& db, const std::function<void(float)>& progress) {
    Impl& im = *impl_;
    WorldScene::PrecacheHooks hooks;
    // The shadow silhouettes (linear memory: they take no VRAM): the placements' (the GL
    // beginLevel's set), then the closure's planar ones (and projected rotations on request).
    const u64 tShadow0 = svcGetSystemTick();
    const pica::ShadowPicaStats ss0 = pica::shadowPicaStats();
    auto shadowHook = [&im](const GpuMesh& mesh, const std::string&, const Material& mat, const ShadowSpec& ss,
                            int steps) {
        if (!pica::renderQuality().blobShadowsOnly) im.precacheShadow(mesh, mat, ss, steps);
    };
    // The closure's: planar ones, the projected ones at step 0, the other rotations only on
    // request (shadow_pica.h).
    auto closureHook = [&im](const GpuMesh& mesh, const std::string&, const Material& mat, const ShadowSpec& ss,
                             int steps) {
        if (pica::renderQuality().blobShadowsOnly) return;
        // Projected: the unrotated one (step 0, the spawns that keep the root's default yaw:
        // mission 1's late ruins_big) always, the other 11 rotations on request.
        if (ss.kind == ShadowKind::Planar || steps == 0 || pica::shadowPrecacheRotations())
            im.precacheShadow(mesh, mat, ss, steps);
    };
    if (const Terrain* t = world.terrain()) {
        if (const LevelData* level = t->level()) {
            for (const Placement& p : level->placements) {
                const ObjectDef* def = im.db->findObject(level->typeName(p));
                im.scene.placedShadows(def, p.rotationSteps, t->style().night, 0, shadowHook);
                // What its script creates takes its yaw, and `create` keys the projected shadow by
                // int(yaw in degrees) mod 12 (builtins_entity.cpp, render-pipeline.md 5.3): an odd
                // rotation gives step 6 (mission 1's ruins_big, late in drop 5).
                const int createKey = ((static_cast<int>(p.yawDegrees()) % 12) + 12) % 12;
                if (createKey != 0) im.scene.spawnedShadows(world, def, createKey, 0, shadowHook);
            }
        }
    }
    const size_t shadowsBefore = im.shadowMaps.size();
    hooks.shadow = closureHook;
    // VRAM goes in creation order (the terrain's textures came
    // with beginLevel): first the models alive now and the level's placements (the player's
    // helicopter is the most drawn texture), then the particle textures (large additive smoke and
    // fire), then the rest of the closure (mostly other helicopters' skins and script spawns).
    hooks.particleTexture = [&im](const std::string& path) { im.particles.preload(path); };
    hooks.particlesFirst = true;
    hooks.drawnFirst = true;
    PrecacheReport r = im.scene.precache(world, db, progress, hooks);
    r.shadows = static_cast<int>(im.shadowMaps.size() - shadowsBefore);
    {
        const double wallMs = static_cast<double>(svcGetSystemTick() - tShadow0) / (SYSCLOCK_ARM11 / 1000.0);
        const pica::ShadowPicaStats& ss = pica::shadowPicaStats();
        const int n = ss.generated - ss0.generated;
        const double genMs = ss.generateMs - ss0.generateMs;
        size_t skinBytes = 0;
        int skinCount = 0;
        for (const auto& kv : im.skins) {
            if (!kv.second) continue;
            ++skinCount;
            skinBytes += static_cast<size_t>(kv.second->width()) * static_cast<size_t>(kv.second->height()) * 4 / 3;
        }
        AS3D_INFO("AS3D_SHADOWS precache: %d silhouettes (%d failed, %d capped to %d), %.1f KB of A8 textures in "
                  "linear memory, generation %.0f ms (%.2f ms each, max %.1f); %d alpha skins on the CPU, about "
                  "%.1f KB; the whole precache %.0f ms",
                  n, ss.failed - ss0.failed, ss.capped - ss0.capped, pica::kMaxShadowSide,
                  static_cast<double>(ss.textureBytes - ss0.textureBytes) / 1024.0, genMs, n > 0 ? genMs / n : 0.0,
                  ss.maxGenerateMs, skinCount, static_cast<double>(skinBytes) / 1024.0, wallMs);
    }
    // Where the model skins went (texture_budget.h): VRAM in creation order until the budget is
    // full, linear memory after. Logged once per level: AS3D_TEXTURES.
    if (const PrecacheSet* set = world.precacheSet()) {
        std::vector<const Texture2D*> seen;
        size_t vramBytes = 0, linearBytes = 0;
        int vram = 0, linear = 0;
        std::string linearNames;
        for (const ObjectDef* def : set->objects) {
            if (def->type != ObjectType::Model || def->model.empty()) continue;
            const Material& m = im.scene.materialFor(*def, std::string());
            if (!m.texture || std::find(seen.begin(), seen.end(), m.texture) != seen.end()) continue;
            seen.push_back(m.texture);
            pica::Placement pl;
            if (!pica::textureInfo(*m.texture, &pl, nullptr, nullptr, nullptr, nullptr)) continue;
            if (pl == pica::Placement::Vram) {
                ++vram;
                vramBytes += m.texture->bytes();
            } else {
                ++linear;
                linearBytes += m.texture->bytes();
                if (linearNames.size() < 600) linearNames += " " + (def->skin.empty() ? def->name : def->skin);
            }
        }
        const pica::TextureStats ts = pica::textureStats();
        AS3D_INFO("AS3D_TEXTURES all: VRAM %d = %.1f KB, linear %d = %.1f KB; model skins: VRAM %d = %.1f KB, linear "
                  "%d = %.1f KB; linear skins:%s",
                  ts.vramCount, static_cast<double>(ts.vramBytes) / 1024.0, ts.linearCount,
                  static_cast<double>(ts.linearBytes) / 1024.0, vram, static_cast<double>(vramBytes) / 1024.0, linear,
                  static_cast<double>(linearBytes) / 1024.0, linearNames.c_str());
    }
    return r;
}

