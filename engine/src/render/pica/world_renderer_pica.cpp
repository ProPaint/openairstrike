void WorldRenderer::render(const World& world, int width, int height, const WorldRenderOptions& options) {
    render(world, 0, 0, width, height, options);
}

void WorldRenderer::render(const World& world, int x, int y, int width, int height, const WorldRenderOptions& options) {
    Viewport vp;
    vp.x = x;
    vp.y = y;
    vp.width = width;
    vp.height = height;
    prepare(world, vp, options);
    draw(EyeView{});
}

const CullFrustum& WorldRenderer::preparedFrustum() const { return impl_->scene.frame().cull; }

void WorldRenderer::prepare(const World& world, const Viewport& viewport, const WorldRenderOptions& options) {
    Impl& im = *impl_;
    WorldScene& sc = im.scene;
    stats_ = WorldRenderStats();
    sc.invalidate();
    if (viewport.width <= 0 || viewport.height <= 0) return;
    using pica::Pass;
    pica::PrepMeter meter;
    const u64 tWorld = svcGetSystemTick();
    const Terrain* terrain = world.terrain();
    im.haveTerrain = terrain && im.terrain && im.terrainOf == terrain;
    // Craters since the last frame (copy-on-write chunks, terrain_pica.h).
    const std::vector<VertexRect>& rects = sc.terrainChanges(world, im.terrainOf);
    if (!rects.empty() && im.terrain) {
        const TerrainGridView grid = TerrainGridView::of(*im.terrainOf);
        im.terrain->update(rects.data(), rects.size(), grid);
        im.waterPass.update(rects.data(), rects.size(), grid); // the wave grid's dry vertices
        im.shadowPass.invalidate(); // the shadows follow the new heights
        im.markPass.invalidate();   // and so do the marks
    }
    meter.lap(Pass::PrepTerrain, static_cast<int>(rects.size()));
    {
        WorldScene::PrepareProfile& sp = sc.profile;
        const WorldScene::PrepareProfile before = sp;
        sc.prepare(world, viewport, options, true, im.haveTerrain, stats_);
        pica::PassProfile& pp = pica::passProfile();
        pp.add(Pass::PrepOrder, sp.order - before.order, 0, 0);
        pp.add(Pass::PrepEntities, sp.entities - before.entities, static_cast<int>(sp.entityCount - before.entityCount), 0);
    }
    meter.lap(Pass::PrepScene, static_cast<int>(sc.lights.size()));
    ++im.prepareSerial;

    // Ground marks (cut again only when the set changes or after a crater) and the skid trails.
    im.markPass.beginFrame();
    if (im.haveTerrain) {
        const TerrainGridView grid = TerrainGridView::of(*terrain);
        im.markPass.setMarks(sc.markDescs, grid);
        ResourceCache& rc = *im.cache;
        const std::vector<SkidTrail>* test = pica::testSkidTrails();
        im.markPass.setSkids(test ? test->data() : sc.skidTrails.data(), test ? test->size() : sc.skidTrailCount, grid,
                             im.skidParams,
                             [&rc](const std::string& path) { return rc.texture(path).texture; });
    }
    meter.lap(Pass::PrepMarks, static_cast<int>(sc.markDescs.size() + sc.skidTrailCount));

    // Water (pass 7) at the world's time, lightning bolts at the camera-independent scroll.
    im.waterPass.prepare(sc.frame().time);
    if (const pica::TestBolts* tb = pica::testBolts()) {
        im.lightningPass.prepare(tb->starts.data(), tb->ends.data(), tb->starts.size(), sc.frame().time,
                                 im.cache->texture("gfx\\lightning2.tga").texture);
    } else {
        im.lightningPass.prepare(sc.boltStarts.data(), sc.boltEnds.data(), sc.boltStarts.size(), sc.frame().time,
                                 sc.frame().boltTexture);
    }
    meter.lap(Pass::PrepWater);

    // Shadows (5.3): a silhouette, or the blob while it is not ready (at most one generated per
    // frame, here, outside the frame; drawn from the next one).
    const u64 tPlace = svcGetSystemTick();
    im.shadowPass.begin();
    int lateBudget = 1, late = 0;
    double lateMs = 0.0;
    if (im.haveTerrain) {
        for (const ShadowRequest& r : sc.shadowRequests) {
            const int steps = r.spec.kind == ShadowKind::Planar ? 0 : r.steps;
            const Impl::ShadowKey key = Impl::shadowKey(*r.mesh, *r.material, r.spec, steps);
            auto found = im.shadowMaps.find(key);
            const bool known = found != im.shadowMaps.end() && found->second.tried;
            const bool generate = !known && lateBudget > 0 && !pica::renderQuality().blobShadowsOnly;
            const double genBefore = pica::shadowPicaStats().generateMs;
            Impl::ShadowEntry& e = im.shadowEntry(*r.mesh, *r.material, key, r.spec, steps, generate);
            if (generate) {
                const double ms = pica::shadowPicaStats().generateMs - genBefore;
                // Which one the precache missed (the first 20 of a level).
                if (im.lateShadowMaps < 20)
                    AS3D_INFO("AS3D_LATE_SHADOW frame=%u model=%s skin=%s kind=%s steps=%d silhouette=%s ms=%.1f",
                              static_cast<unsigned>(im.prepareSerial), r.modelPath ? r.modelPath->c_str() : "?",
                              r.skinPath && !r.skinPath->empty() ? r.skinPath->c_str() : "-",
                              r.spec.kind == ShadowKind::Planar ? "planar" : "projected", steps,
                              e.map ? "yes" : "no", ms);
                lateMs += ms;
                --lateBudget;
                ++late;
                ++im.lateShadowMaps;
                LoadStats::count(LoadKind::Shadow, r.modelPath ? r.modelPath->c_str() : nullptr, "shadow"); // a first-use load (as3d/load_stats.h)
            }
            if (e.tried && !e.map) continue; // no silhouette (no faces): no shadow, as GL
            const bool isStatic = r.spec.kind == ShadowKind::Projected; // at the spawn origin
            if (e.map && e.readyAt <= im.prepareSerial)
                im.shadowPass.add(&e.map->texture, shadowRect(*e.map, r.origin, r.yawDegrees), false, isStatic,
                                  &e.atlas);
            else if (e.bounds.xmax > e.bounds.xmin && e.bounds.ymax > e.bounds.ymin)
                im.shadowPass.add(&im.shadowPass.blob(), shadowRect(e.bounds, e.kind, r.origin, r.yawDegrees), true,
                                  isStatic);
        }
        const u64 tDrape = svcGetSystemTick();
        im.shadowPass.build(TerrainGridView::of(*terrain));
        pica::passProfile().add(Pass::PrepDrape, svcGetSystemTick() - tDrape, pica::shadowPicaStats().drapedNow, 0);
    }
    pica::noteShadowFrame(late, static_cast<double>(svcGetSystemTick() - tPlace) / (SYSCLOCK_ARM11 / 1000.0) - lateMs);
    stats_.shadows = static_cast<int>(im.shadowPass.shadowCount());
    meter.lap(Pass::PrepShadows, static_cast<int>(sc.shadowRequests.size()));
    // The mesh passes: all per-model CPU work (cube colours, material keys) once per frame.
    const SceneLighting& light = sc.frame().light;
    im.opaquePass.begin(light, sc.lights.data(), sc.lights.size());
    im.opaquePass.setEnvironment(sc.frame().wv.view, sc.frame().time, im.rules.envViewNormal);
    im.restPass.setEnvironment(sc.frame().wv.view, sc.frame().time, im.rules.envViewNormal);
    for (const MeshRecord& r : sc.opaque) im.opaquePass.submit(*r.mesh, *r.material, r.model, r.colour);
    im.opaquePass.finish();
    im.restPass.begin(light, sc.lights.data(), sc.lights.size());
    for (const MeshRecord& r : sc.trans) im.restPass.submit(*r.mesh, *r.material, r.model, r.colour);
    for (const MeshRecord& r : sc.effect) im.restPass.submit(*r.mesh, *r.material, r.model, r.colour);
    im.restPass.finish();
    meter.lap(Pass::PrepMeshes, static_cast<int>(im.opaquePass.size() + im.restPass.size()));
    // Which of this frame's model textures live in linear memory (the VRAM split).
    pica::WorldPicaStats& ws = pica::g_worldStats;
    ws.records = ws.linearRecords = 0;
    ws.linearSkins.clear();
    for (const std::vector<MeshRecord>* list : {&sc.opaque, &sc.trans, &sc.effect}) {
        for (const MeshRecord& r : *list) {
            ++ws.records;
            pica::Placement pl;
            if (r.material->texture && pica::textureInfo(*r.material->texture, &pl, nullptr, nullptr, nullptr, nullptr) &&
                pl == pica::Placement::Linear) {
                ++ws.linearRecords;
                const std::string& name = world.entity(r.entity).def->name;
                if (ws.linearSkins.find(" " + name) == std::string::npos && ws.linearSkins.size() < 400)
                    ws.linearSkins += " " + name;
            }
        }
    }
    meter.lap(Pass::PrepStats, ws.linearRecords);
    pica::passProfile().add(Pass::PrepWorld, svcGetSystemTick() - tWorld, 0, 0);
}

void WorldRenderer::draw(const EyeView& eye) {
    const Viewport& vp = impl_->scene.frame().viewport;
    draw(eye, vp.x, vp.y);
}

void WorldRenderer::draw(const EyeView& eye, int vx, int vy) {
    Impl& im = *impl_;
    const WorldScene& sc = im.scene;
    const WorldScene::Frame& fr = sc.frame();
    stats_.terrainChunks = stats_.waterChunks = stats_.skidTrails = stats_.bolts = 0;
    stats_.emitters = stats_.particles = 0;
    if (!fr.ready) return;
    const WorldRenderOptions& options = fr.options;
    const SceneLighting& light = fr.light;
    const WorldView& wv = fr.wv;

    // The eye: the central view with the eye's stereo projection (pica_frame.h).
    const Mat4 proj = pica::picaEyeProjection(wv, eye, fr.aspect);
    const Mat4 viewProj = proj * wv.view;
    auto levelDepthAndFog = [&]() {
        pica::setDepthMapping(FogDepthMap::WBuffer, wv.nearPlane);
        pica::setLevelFogColor(light.fogColor);
        if (fr.hasFog) pica::setFog(wv.nearPlane, wv.farPlane, light.fogStart, light.fogEnd);
        else pica::disableFog();
    };

    using pica::Pass;
    using pica::passEnabled;
    pica::PassMeter meter(stats_);
    meter.start(Pass::Clear);
    // Pass 0: clear to the fog colour (black without fog).
    setViewport(vx, vy, fr.viewport.width, fr.viewport.height);
    const Vec3 cc = fr.clearColour;
    clear(Vec4{cc.x, cc.y, cc.z, 1.0f}, true, 1.0f);
    setBlend(GlBlend::Off);
    setDepth(true, true);
    setCull(CullMode::Back);
    levelDepthAndFog();

    // Pass 2: terrain.
    meter.start(Pass::Terrain);
    if (options.terrain && im.haveTerrain && passEnabled(Pass::Terrain)) {
        TerrainViewParams tv;
        tv.view = wv.view;
        tv.projection = proj;
        tv.cameraPos = eyePosition(wv, eye);
        tv.fogColour = light.fogColor;
        tv.fogStart = light.fogStart;
        tv.fogEnd = light.fogEnd;
        tv.time = fr.time;
        tv.mapPos = fr.mapPos;
        tv.lights = sc.lights.data();
        tv.lightCount = sc.lights.size();
        im.terrain->render(tv);
        stats_.terrainChunks = im.terrain->lastVisibleChunks();
        const pica::TerrainPicaStats& ts = pica::terrainPicaStats();
        stats_.drawCalls += ts.drawCalls;
        stats_.vertices += static_cast<int>(ts.indicesDrawn);
        levelDepthAndFog();
    }
    setDepth(true, true);
    setCull(CullMode::Back);
    // Pass 4: ground marks, then the sequels' skid trails (between the marks and the shadows).
    meter.start(Pass::Marks);
    if (im.haveTerrain && im.markPass.active() && passEnabled(Pass::Marks)) {
        stats_.drawCalls += im.markPass.draw(wv.view, proj, light.fogColor, fr.hasFog ? light.fogStart : 1.0e9f,
                                             fr.hasFog ? light.fogEnd : 1.0e9f);
        stats_.skidTrails = pica::markPicaStats().skidTrails;
        levelDepthAndFog();
        setDepth(true, true);
        setCull(CullMode::Back);
    }
    // Pass 5: shadows. The level's depth mapping and fog are in place (the passes before
    // restored them).
    meter.start(Pass::Shadows);
    if (im.haveTerrain && im.shadowPass.shadowCount() > 0 && passEnabled(Pass::Shadows)) {
        const int drawsBefore = pica::shadowPicaStats().draws;
        im.shadowPass.draw(viewProj);
        stats_.drawCalls += pica::shadowPicaStats().draws - drawsBefore;
        stats_.vertices += pica::shadowPicaStats().vertices;
        setDepth(true, true);
        setCull(CullMode::Back);
    }
    // Pass 6: opaque list; pass 7: water; passes 8 and 9: transparent then effect list.
    meter.start(Pass::Opaque);
    if (passEnabled(Pass::Opaque)) {
        im.opaquePass.draw(viewProj);
        stats_.drawCalls += im.opaquePass.lastStats().draws;
        stats_.vertices += im.opaquePass.lastStats().vertices;
    }
    meter.start(Pass::Water);
    if (options.terrain && options.water && im.haveTerrain && im.waterPass.active() && passEnabled(Pass::Water)) {
        stats_.drawCalls += im.waterPass.draw(wv.view, proj, light.fogColor, fr.hasFog ? light.fogStart : 1.0e9f,
                                              fr.hasFog ? light.fogEnd : 1.0e9f);
        const pica::WaterPicaStats& wst = pica::waterPicaStats();
        stats_.waterChunks = wst.quadsDrawn;
        stats_.vertices += wst.grid ? wst.trianglesDrawn * 3 : wst.quadsDrawn * 6;
        levelDepthAndFog();
        setBlend(GlBlend::Off);
        setDepth(true, true);
        setCull(CullMode::Back);
    }
    meter.start(Pass::Rest);
    if (passEnabled(Pass::Rest)) {
        im.restPass.draw(viewProj);
        stats_.drawCalls += im.restPass.lastStats().draws;
        stats_.vertices += im.restPass.lastStats().vertices;
    }
    setBlend(GlBlend::Off);
    setDepth(true, true);
    setCull(CullMode::Back);
    // Lightning bolts, after the effect models (7.1).
    meter.start(Pass::Lightning);
    if (options.lightning && im.lightningPass.active() && passEnabled(Pass::Lightning)) {
        stats_.drawCalls += im.lightningPass.draw(wv.view, proj, light.fogColor, fr.hasFog ? light.fogStart : 1.0e9f,
                                                  fr.hasFog ? light.fogEnd : 1.0e9f);
        stats_.bolts = pica::lightningPicaStats().bolts;
        stats_.vertices += pica::lightningPicaStats().vertices;
        levelDepthAndFog();
        setBlend(GlBlend::Off);
        setDepth(true, true);
        setCull(CullMode::Back);
    }
    // Pass 10: particles.
    meter.start(Pass::Particles);
    if (options.particles && passEnabled(Pass::Particles)) {
        ParticleViewParams pv;
        pv.view = wv.view;
        pv.projection = proj;
        pv.fogColour = light.fogColor;
        pv.fogStart = light.fogStart;
        pv.fogEnd = light.fogEnd;
        if (!sc.emitters.empty()) {
            im.particles.draw(sc.emitters.data(), sc.emitters.size(), pv);
            const pica::FxPicaStats& fs = pica::fxPicaStats();
            stats_.drawCalls += fs.particleDraws;
            stats_.vertices += fs.particleQuads * 6;
        }
        stats_.emitters = static_cast<int>(sc.emitters.size());
        stats_.particles = im.particles.lastParticleCount();
    }
    // Pass 12: sprites.
    meter.start(Pass::Sprites);
    if (!sc.sprites.empty() && passEnabled(Pass::Sprites)) {
        SpriteViewParams sv;
        sv.view = wv.view;
        sv.projection = proj;
        sv.fogColour = light.fogColor;
        sv.fogStart = light.fogStart;
        sv.fogEnd = light.fogEnd;
        sv.cullBackFaces = im.rules.spriteCulling;
        im.sprites.draw(sc.sprites.data(), sc.sprites.size(), sv);
        const pica::FxPicaStats& fs = pica::fxPicaStats();
        stats_.drawCalls += fs.spriteDraws;
        stats_.vertices += fs.spriteQuads * 6;
    }
    setBlend(GlBlend::Off);
    setDepth(true, true);
    setCull(CullMode::Back);
    pica::disableFog();
}

void WorldRenderer::drawBrightness(int width, int height, float brightness) { drawBrightness(0, 0, width, height, brightness); }

// Pass 14 (render-pipeline.md 1.5): dst * b + b * dst, the blend (DST_COLOR, SRC_COLOR) of
// RenderBlend::Brightness, over the rectangle (GL convention: y from the bottom).
void WorldRenderer::drawBrightness(int x, int y, int width, int height, float brightness) {
    if (brightness <= 0.0f || width <= 0 || height <= 0) return;
    const pica::FrameTarget& t = pica::currentTarget();
    MaterialKey key;
    key.blend = RenderBlend::Brightness;
    key.depthTest = false;
    key.depthWrite = false;
    key.cull = CullMode::Off;
    const uint8_t b = static_cast<uint8_t>(std::min(brightness, 1.0f) * 255.0f + 0.5f);
    const float top = static_cast<float>(t.height - y - height);
    pica::fillRect(static_cast<float>(x), top, static_cast<float>(x + width), top + static_cast<float>(height), b, b, b,
                   255, key);
    setBlend(GlBlend::Off);
    setDepth(true, true);
    setCull(CullMode::Back);
}

