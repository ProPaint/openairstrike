#!/usr/bin/env python3
"""Converts the console menus' key pictures (apps/3ds/assets/keys.png: the owner's set 4, "HUD plate",
original art of this project, docs/3ds-ui-design.md "Owner decisions") into apps/3ds/assets/keys.inc,
the C initialisers apps/3ds/source/key_glyphs.cpp embeds (a palette and one index byte per pixel; the
engine decodes no PNG). Run it after changing keys.png:

    python3 -I tools/3ds_key_glyphs.py
"""
import os
import sys

from PIL import Image

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, "apps", "3ds", "assets", "keys.png")
DST = os.path.join(REPO, "apps", "3ds", "assets", "keys.inc")


def main():
    im = Image.open(SRC).convert("RGBA")
    w, h = im.size
    if w > 256 or h > 32:
        sys.exit("keys.png must fit 256 x 32 (it is %d x %d)" % (w, h))
    pixels = [im.getpixel((x, y)) for y in range(h) for x in range(w)]
    palette = sorted(set(pixels))
    if len(palette) > 256:
        sys.exit("keys.png has %d colours (at most 256)" % len(palette))
    index = {c: i for i, c in enumerate(palette)}
    out = ["// Generated by tools/3ds_key_glyphs.py from keys.png (original art of this project). Do not edit.",
           "constexpr int kKeysW = %d, kKeysH = %d;" % (w, h),
           "constexpr unsigned kKeysPalette[] = {  // 0xRRGGBBAA"]
    for i in range(0, len(palette), 8):
        out.append("    " + " ".join("0x%02x%02x%02x%02xu," % c for c in palette[i:i + 8]))
    out.append("};")
    out.append("constexpr unsigned char kKeysIndex[] = {  // rows from the top")
    for y in range(h):
        row = [index[pixels[y * w + x]] for x in range(w)]
        for i in range(0, w, 24):
            out.append("    " + ",".join("%d" % v for v in row[i:i + 24]) + ",")
    out.append("};")
    with open(DST, "w") as f:
        f.write("\n".join(out) + "\n")
    print("3ds_key_glyphs: %s (%d x %d, %d colours)" % (DST, w, h, len(palette)))


if __name__ == "__main__":
    main()
